package io.karpfen.ide.core.document.fixtures

/**
 * Generates large, syntactically valid KStates documents for the time-budget tests and benchmarks of the parse
 * pipeline and the editor.
 *
 * A document with `n` states contains the states `s0` to `s(n-1)`. `s0` is the single INITIAL state. Every state whose
 * index is divisible by 10 nests up to nine of the states that follow it. The states have ENTRY and DO blocks with
 * SET, APPEND and EVENT actions and multi-line EVAL bodies. These bodies hold Python with `$(...)` paths, `#` comments
 * and `@macro(...)` calls. The document also has `IF IN SCOPE` and `WITH ... AS` blocks, one transition per state with
 * an EVENT, VALUE or EVAL condition, SPLIT and JOIN pairs and a MACROS block. The output is deterministic and also
 * converts with the `KstatesDSLConverter` of dsl-tools.
 */
public object SyntheticKstates {

    /** The type the generated machine is attached to. */
    public const val ATTACHED_TYPE: String = "Robot"

    /** Same as [generate]. It lets callers write `SyntheticKstates(5000)`. */
    public operator fun invoke(stateCount: Int): String = generate(stateCount)

    /** The name of the state with [index]. */
    public fun stateName(index: Int): String = "s$index"

    /** A document with [stateCount] states. [stateCount] must be at least 1. */
    public fun generate(stateCount: Int): String {
        require(stateCount >= 1) { "stateCount must be >= 1, was $stateCount" }
        val out = StringBuilder()
        out.appendLine("// Synthetic KStates document with $stateCount states, generated by SyntheticKstates.")
        out.appendLine("STATEMACHINE ATTACHED TO \"$ATTACHED_TYPE\" {")
        out.appendLine()
        out.appendLine("    STATES {")
        var index = 0
        while (index < stateCount) {
            val childCount = minOf(9, stateCount - index - 1)
            appendState(out, index, indent = 2, children = (index + 1)..(index + childCount))
            index += childCount + 1
        }
        out.appendLine("    }")
        out.appendLine()
        out.appendLine("    TRANSITIONS {")
        for (i in 0 until stateCount) appendTransitions(out, i, stateCount)
        out.appendLine("    }")
        out.appendLine()
        appendMacros(out)
        out.appendLine("}")
        return out.toString()
    }

    /**
     * The smallest generated document with at least [minLines] lines. The search counts the states upwards until the
     * document is long enough.
     */
    public fun withMinLines(minLines: Int): String {
        require(minLines >= 1) { "minLines must be >= 1, was $minLines" }
        var count = maxOf(1, minLines / LINES_PER_STATE_ESTIMATE)
        var text = generate(count)
        while (lineCount(text) < minLines) {
            count += maxOf(1, (minLines - lineCount(text)) / LINES_PER_STATE_ESTIMATE)
            text = generate(count)
        }
        return text
    }

    /** The number of lines of [text], separated by `\n`. */
    public fun lineCount(text: String): Int = text.count { it == '\n' } + 1

    private const val LINES_PER_STATE_ESTIMATE = 30

    private fun appendState(out: StringBuilder, index: Int, indent: Int, children: IntRange) {
        val pad = "    ".repeat(indent)
        val name = stateName(index)
        val initial = if (index == 0) "INITIAL " else ""
        out.appendLine("$pad${initial}STATE \"$name\" {")
        out.appendLine("$pad    ENTRY {")
        out.appendLine("$pad        SET(\"counter\", \"$index\")")
        out.appendLine("$pad        APPEND(\"log\", \"entered $name\")")
        if (index % 3 == 1) {
            out.appendLine("$pad        IF IN SCOPE(\"closest_obstacle\") {")
            out.appendLine("$pad            SET(\"distance\", MACRO(\"dist\", \"position\", \"closest_obstacle->position\"))")
            out.appendLine("$pad        }")
        }
        out.appendLine("$pad    }")
        out.appendLine("$pad    DO {")
        out.appendLine("$pad        SET(\"value\", EVAL {")
        out.appendLine("$pad            # step $index of the synthetic machine")
        out.appendLine("$pad            x = \$(value) + $index")
        out.appendLine("$pad            if x > 1000:")
        out.appendLine("$pad                x = x - 1000")
        out.appendLine("$pad            return x")
        out.appendLine("$pad        })")
        if (index % 7 == 2) {
            out.appendLine("$pad        WITH MACRO(\"dist\", \"position\", \"target->position\") AS \"d\" {")
            out.appendLine("$pad            SET(\"distance\", EVAL { return \$(d) * 2 })")
            out.appendLine("$pad        }")
        }
        out.appendLine("$pad        EVENT(\"public\", \"tick\")")
        out.appendLine("$pad    }")
        for (child in children) appendState(out, child, indent + 1, IntRange.EMPTY)
        out.appendLine("$pad}")
    }

    private fun appendTransitions(out: StringBuilder, index: Int, stateCount: Int) {
        val from = stateName(index)
        val to = stateName((index + 1) % stateCount)
        val looping = if (index % 2 == 0) " NOT LOOPING" else ""
        out.appendLine("        TRANSITION \"$from\" -> \"$to\"$looping {")
        out.appendLine("            CONDITION {")
        when (index % 4) {
            0 -> out.appendLine("                EVENT(\"public\", \"tick\")")
            1 -> out.appendLine("                VALUE(\"flag\")")
            else -> out.appendLine("                EVAL { return \$(value) > $index and @dist(\$(position), \$(target->position)) < 1.0 }")
        }
        out.appendLine("            }")
        out.appendLine("        }")
        if (index % 50 == 0 && index + 3 < stateCount) {
            val a = stateName(index + 1)
            val b = stateName(index + 2)
            val c = stateName(index + 3)
            out.appendLine("        SPLIT \"$from\" -> \"$a\", \"$b\" { }")
            out.appendLine("        JOIN \"$a\", \"$b\" -> \"$c\" NOT LOOPING { }")
        }
    }

    private fun appendMacros(out: StringBuilder) {
        out.appendLine("    MACROS {")
        out.appendLine("        MACRO \"dist\" {")
        out.appendLine("            TAKES(\"a\", \"Vector\")")
        out.appendLine("            TAKES(\"b\", \"Vector\")")
        out.appendLine("            RETURNS(\"number\")")
        out.appendLine("            DEFINITION {")
        out.appendLine("                EVAL {")
        out.appendLine("                    import math")
        out.appendLine("                    return math.sqrt((\$(a->x) - \$(b->x)) ** 2 + (\$(a->y) - \$(b->y)) ** 2)")
        out.appendLine("                }")
        out.appendLine("            }")
        out.appendLine("        }")
        out.appendLine("        MACRO \"closest\" {")
        out.appendLine("            TAKES(\"origin\", \"Vector\")")
        out.appendLine("            TAKES(\"candidates\", list(\"Obstacle\"))")
        out.appendLine("            RETURNS(reference(\"Obstacle\"))")
        out.appendLine("            DEFINITION {")
        out.appendLine("                EVAL {")
        out.appendLine("                    best = None")
        out.appendLine("                    for c in \$(candidates) :")
        out.appendLine("                        if best is None or @dist(\$(origin), \$(c->position)) < @dist(\$(origin), \$(best->position)) :")
        out.appendLine("                            best = c")
        out.appendLine("                    return best")
        out.appendLine("                }")
        out.appendLine("            }")
        out.appendLine("        }")
        out.appendLine("    }")
    }
}
